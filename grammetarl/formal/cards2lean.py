r"""Emit genuine Lean 4 certificates: the compiled automaton itself, plus kernel-checked claims.

For each formalizable constraint we emit the automaton (states, transition table over an explicit
sub-alphabet, accepting predicate) and two kinds of theorem:

  witness       run_{key} <witness> = true
                -- the kernel re-executes the automaton; this is not a transcription check
  bounded_none  (stringsUpTo d).all (fun w => run_{key} w = false)
                -- a bounded model check over the card's OWN sub-alphabet, with d chosen so the
                -- enumeration stays inside kernel budget

Honest scope, stated in the generated file too: the Python DFA analysis is complete modulo SIGMA*
(unbounded length, corpus alphabet); the Lean certificate is complete only up to depth d over the
card's sub-alphabet. That gap is exactly the T2/T3 distinction the P6 plan is built on.
"""
from __future__ import annotations

from dataclasses import dataclass

from .regex_dfa import DFA, END, START, UnsupportedRegex, compile_pattern, normalize_anchor

MAX_STATES = 45
SUBALPHA_CAP = 12
ENUM_BUDGET = 2500  # |Sigma_card|^depth cap for the bounded enumeration


@dataclass(slots=True)
class Emitted:
    card_id: str
    index: int
    kind: str
    status: str
    n_states: int
    subalphabet: str
    depth: int
    claims: list[str]


def _safe(cid: str, idx: int) -> str:
    return f"{cid.replace('/', '_').replace('-', '_')}_{idx}"


def _depth_for(alpha_size: int) -> int:
    d = 2
    while alpha_size ** (d + 1) <= ENUM_BUDGET and d < 6:
        d += 1
    return d


def emit_lean(cards, facts_by_card: dict[str, list[dict]], alpha, max_claims: int = 30) -> tuple[str, list[Emitted]]:
    sigma = tuple(c for c in alpha.chars if c not in (START, END))
    char_id = {c: i + 1 for i, c in enumerate(sigma)}
    lines = [
        "-- Generated by grammetarl/formal/cards2lean.py -- do not edit by hand.",
        f"-- Alphabet ids: {' '.join(f'{char_id[c]}={c!r}' for c in sigma[:24])}",
        f"-- BOUNDED-MODEL BOUND: 'bounded_none' theorems quantify over strings of length <= d",
        "-- over that card's sub-alphabet only (d is printed per automaton).",
        "set_option maxRecDepth 8000",
        "set_option maxHeartbeats 4000000",
        "namespace GramMetaRL",
        "",
        "def SIGMA : List Nat := [" + ", ".join(str(char_id[c]) for c in sigma) + "]",
        "",
        "def stringsUpTo : Nat -> List (List Nat)",
        "  | 0 => [[]]",
        "  | n + 1 => (SIGMA.flatMap fun a => (stringsUpTo n).map fun w => a :: w)",
        "",
        "-- generic runner: fold the transition function, then test acceptance",
        "def runWith (step : Nat -> Nat -> Nat) (init : Nat) (fin : Nat -> Bool)",
        "    (w : List Nat) : Bool := fin (w.foldl step init)",
        "",
    ]
    emitted: list[Emitted] = []
    case_blocks: list[str] = []
    made = 0
    for card in cards:
        for idx, fact in enumerate(facts_by_card.get(card.id, [])):
            if made >= max_claims:
                break
            if fact["kind"] not in ("must_include_regex", "must_exclude_regex") or not fact.get("pattern"):
                continue
            try:
                raw = fact["pattern"]
                # Same anchor convention as the analysis: explicit wrapping, never silent stripping.
                pat, infix = normalize_anchor(raw)
                anchored = not infix
                # sub-alphabet = chars the pattern mentions, so the bounded enumeration is meaningful
                sub = sorted({c for c in pat if c in char_id} | {c for c in pat.lower() if c in char_id})
                sub = sub[:SUBALPHA_CAP] or list(sigma[:6])
                sub_alpha = tuple(sub)
                nfa = compile_pattern(pat, sub_alpha, search=not anchored)
                dfa = DFA(nfa, sub_alpha)
            except UnsupportedRegex:
                continue
            if len(dfa.states) > MAX_STATES or dfa.overflow:
                continue
            key = _safe(card.id, idx)
            case_start = len(lines)
            states = list(dfa.states)
            sid = {s: (0 if s == dfa.start else i + 1) for i, s in enumerate(states) if s != dfa.start}
            sid[dfa.start] = 0
            # dead_id must not alias a real state id: ids are 0..max(sid.values()), so take max+1
            dead_id = max(sid.values()) + 1
            lines.append(f"-- card {card.id} constraint #{idx} kind={fact['kind']} "
                         f"status={fact['status']} pattern={pat!r}")
            lines.append(f"def step_{key} : Nat -> Nat -> Nat")
            any_row = False
            for s, si in sorted(sid.items(), key=lambda kv: kv[1]):
                for c in sub_alpha:
                    nxt = dfa.trans.get((s, c), frozenset())
                    if not nxt:
                        continue
                    tgt = sid.get(nxt, dead_id)
                    if tgt != si or True:
                        lines.append(f"  | {si}, {char_id.get(c, 0)} => {tgt}")
                        any_row = True
            lines.append(f"  | _, _ => {dead_id}")
            lines.append(f"def fin_{key} : Nat -> Bool")
            finals = sorted(sid[s] for s in dfa.finals if s in sid)
            if finals:
                for f in finals:
                    lines.append(f"  | {f} => true")
            lines.append("  | _ => false")
            lines.append(f"def run_{key} : List Nat -> Bool := runWith step_{key} 0 fin_{key}")
            # enumeration over THIS automaton's sub-alphabet, so the bound is both honest and cheap
            sub_ids = [char_id[c] for c in sub if c in char_id]
            lines.append(f"def SIGMA_{key} : List Nat := [" + ", ".join(str(x) for x in sub_ids) + "]")
            lines.append(f"def strs_{key} : Nat -> List (List Nat)")
            lines.append("  | 0 => [[]]")
            lines.append(f"  | n + 1 => (SIGMA_{key}.flatMap fun a => (strs_{key} n).map fun w => a :: w)")
            claims = []
            wit = dfa.witness()
            enc = [char_id[c] for c in (wit or "") if c in char_id]
            if enc:
                lst = "[" + ", ".join(str(x) for x in enc) + "]"
                lines.append(f"theorem witness_{key} : run_{key} {lst} = true := by decide")
                claims.append(f"witness={''.join(c for c in wit if c in char_id)!r}")
                # minimality: nothing shorter than the DFA's shortest word is accepted
                k = len(enc) - 1
                # Only emit a claim our own model already supports: Lean is then an independent
                # second opinion, and a Lean failure means an encoding bug rather than a claim the
                # Python model never made. (Under re.search semantics an epsilon-matching pattern
                # is accepted by every string, so naive minimality claims are simply false.)
                import itertools as _it
                shorter_ok = True
                for depth in range(0, k + 1):
                    for tup in _it.product(sub, repeat=depth):
                        if dfa.accepts("".join(tup)):
                            shorter_ok = False
                            break
                    if not shorter_ok:
                        break
                # enumeration cost guard: the kernel must stay inside budget
                if k >= 0 and shorter_ok and (max(2, len(sub)) ** k) <= ENUM_BUDGET:
                    lines.append(f"theorem minimal_{key} :")
                    lines.append(f"  (strs_{key} {k}).all (fun w => run_{key} w = false) := by decide")
                    claims.append(f"minimal_at_depth={k}")
            else:
                d = _depth_for(max(2, len(sub)))
                lines.append(f"theorem dead_bounded_{key} :")
                lines.append(f"  (strs_{key} {d}).all (fun w => run_{key} w = false) := by decide")
                claims.append(f"no_match_up_to_depth={d} over |sub|={len(sub)}")
            lines.append("")
            depth_used = (len(enc) - 1) if enc else _depth_for(max(2, len(sub)))
            emitted.append(Emitted(card.id, idx, fact["kind"], fact["status"], len(sid),
                                   "".join(sub), depth_used, claims))
            # each case is returned as a self-contained block: splitting a single generated file
            # by marker used to cut definitions in half ("invalid 'end', insufficient scopes")
            case_blocks.append("\n".join(lines[case_start:]))
            made += 1
        if made >= max_claims:
            break
    lines.append("end GramMetaRL")
    return "\n".join(lines) + "\n", emitted, case_blocks
